package com.jt.naicenotes.data.sync

/**
 * Port of the npm `fractional-indexing` package (v4, default alphabets) that the PWA uses.
 *
 * Order keys are strings compared bytewise: adding at the top is `keyBetween(null, first)`, a
 * drag is one write for the moved row, and nothing else in the section is renumbered. That's
 * what makes ordering sync-friendly — renumbering every row on each add (the old `position`
 * scheme) would push N row updates and scramble when two people add at once.
 *
 * Must stay key-for-key identical to the JS package: the PWA validates every key it reads and
 * throws on one it considers malformed. `FractionalIndexTest` pins outputs generated by the JS
 * package itself.
 */
object FractionalIndex {
    private const val DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
    private const val INT_DIGITS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
    private const val ZERO = '0'
    private val SMALLEST_INTEGER = INT_DIGITS[0] + ZERO.toString().repeat(INT_DIGITS.length / 2)

    private fun digit(c: Char): Int = DIGITS.indexOf(c)

    fun isValid(key: String): Boolean = runCatching { validateOrderKey(key) }.isSuccess

    /**
     * A key strictly between [a] and [b] (either may be null for an open end). The JS package
     * swaps reversed bounds; so does this. Equal bounds throw — use [keyBetweenSafe] when the
     * bounds come from data two devices may have written concurrently.
     */
    fun keyBetween(a: String?, b: String?): String {
        a?.let(::validateOrderKey)
        b?.let(::validateOrderKey)
        var lo = a
        var hi = b
        if (lo != null && hi != null && lo > hi) {
            lo = b
            hi = a
        }

        if (lo == null) {
            if (hi == null) return INT_DIGITS[INT_DIGITS.length / 2].toString() + ZERO
            val ib = integerPart(hi)
            val fb = hi.substring(ib.length)
            if (ib == SMALLEST_INTEGER) return ib + midpoint("", fb)
            if (ib < hi) return ib
            return decrementInteger(ib) ?: error("cannot decrement any more")
        }

        if (hi == null) {
            val ia = integerPart(lo)
            val fa = lo.substring(ia.length)
            return incrementInteger(ia) ?: (ia + midpoint(fa, null))
        }

        val ia = integerPart(lo)
        val fa = lo.substring(ia.length)
        val ib = integerPart(hi)
        val fb = hi.substring(ib.length)
        if (ia == ib) return ia + midpoint(fa, fb)
        val i = incrementInteger(ia) ?: error("cannot increment any more")
        if (i < hi) return i
        return ia + midpoint(fa, null)
    }

    /** [n] distinct keys between [a] and [b], ascending. Same output as `generateNKeysBetween`. */
    fun nKeysBetween(a: String?, b: String?, n: Int): List<String> {
        if (n <= 0) return emptyList()
        if (n == 1) return listOf(keyBetween(a, b))
        if (b == null) {
            var c = keyBetween(a, null)
            val out = mutableListOf(c)
            repeat(n - 1) {
                c = keyBetween(c, null)
                out += c
            }
            return out
        }
        if (a == null) {
            var c = keyBetween(null, b)
            val out = mutableListOf(c)
            repeat(n - 1) {
                c = keyBetween(null, c)
                out += c
            }
            return out.reversed()
        }
        val mid = n / 2
        val c = keyBetween(a, b)
        return nKeysBetween(a, c, mid) + c + nKeysBetween(c, b, n - mid - 1)
    }

    /**
     * Like the PWA's `keyBetween` in notes.ts: two devices inserting at the same spot can leave
     * equal neighbours, and a strict "between" doesn't exist then. Lands just after [a]; the
     * createdAt/uuid tie-break keeps the order stable.
     */
    fun keyBetweenSafe(a: String?, b: String?): String =
        if (a != null && b != null && a >= b) keyBetween(a, null) else keyBetween(a, b)

    // ── Internals, line for line with the JS source ──

    private fun midpoint(a: String, b: String?): String {
        if (b != null && a >= b) throw IllegalArgumentException("$a >= $b")
        if (a.lastOrNull() == ZERO || (b != null && b.lastOrNull() == ZERO)) {
            throw IllegalArgumentException("trailing zero")
        }
        if (b != null) {
            var n = 0
            while (n < b.length && (a.getOrNull(n) ?: ZERO) == b[n]) n++
            if (n > 0) return b.substring(0, n) + midpoint(a.substring(n), b.substring(n))
        }
        val digitA = if (a.isNotEmpty()) digit(a[0]) else 0
        val digitB = if (b != null) digit(b[0]) else DIGITS.length
        return if (digitB - digitA > 1) {
            // Math.round(0.5 * (a + b)) for non-negative ints.
            DIGITS[(digitA + digitB + 1) / 2].toString()
        } else if (b != null && b.length > 1) {
            b.substring(0, 1)
        } else {
            DIGITS[digitA] + midpoint(if (a.isEmpty()) "" else a.substring(1), null)
        }
    }

    private fun integerLength(head: Char): Int {
        val i = INT_DIGITS.indexOf(head)
        if (i < 0) throw IllegalArgumentException("invalid order key head: $head")
        val half = INT_DIGITS.length / 2
        return if (i < half) half - i + 1 else i - half + 2
    }

    private fun validateInteger(int: String) {
        if (int.length != integerLength(int[0])) {
            throw IllegalArgumentException("invalid integer part of order key: $int")
        }
    }

    private fun integerPart(key: String): String {
        if (key.isEmpty()) throw IllegalArgumentException("invalid order key: empty")
        val len = integerLength(key[0])
        if (len > key.length) throw IllegalArgumentException("invalid order key: $key")
        return key.substring(0, len)
    }

    private fun validateOrderKey(key: String) {
        if (key == SMALLEST_INTEGER) throw IllegalArgumentException("invalid order key: $key")
        if (key.any { digit(it) < 0 }) {
            throw IllegalArgumentException("invalid order key: $key")
        }
        val i = integerPart(key)
        val f = key.substring(i.length)
        if (f.lastOrNull() == ZERO) throw IllegalArgumentException("invalid order key: $key")
    }

    private fun incrementInteger(x: String): String? {
        validateInteger(x)
        val head = x[0]
        var trailing = ""
        for (i in x.length - 1 downTo 1) {
            val d = digit(x[i]) + 1
            if (d == DIGITS.length) {
                trailing = ZERO + trailing
            } else {
                return head + x.substring(1, i) + DIGITS[d] + trailing
            }
        }
        val headIndex = INT_DIGITS.indexOf(head)
        if (headIndex == INT_DIGITS.length - 1) return null
        val h = INT_DIGITS[headIndex + 1]
        val delta = integerLength(h) - integerLength(head)
        return h + when {
            delta > 0 -> trailing + ZERO
            delta < 0 -> trailing.substring(1)
            else -> trailing
        }
    }

    private fun decrementInteger(x: String): String? {
        validateInteger(x)
        val head = x[0]
        val last = DIGITS.last()
        var trailing = ""
        for (i in x.length - 1 downTo 1) {
            val d = digit(x[i]) - 1
            if (d == -1) {
                trailing = last + trailing
            } else {
                return head + x.substring(1, i) + DIGITS[d] + trailing
            }
        }
        val headIndex = INT_DIGITS.indexOf(head)
        if (headIndex == 0) return null
        val h = INT_DIGITS[headIndex - 1]
        val delta = integerLength(h) - integerLength(head)
        return h + when {
            delta > 0 -> trailing + last
            delta < 0 -> trailing.substring(1)
            else -> trailing
        }
    }
}

/**
 * New keys for a list whose display order changed, writing as few rows as possible.
 *
 * [keys] are the rows' current keys in their **new** order. The longest strictly increasing
 * run of them is already in order and keeps its keys; every other row gets a fresh key between
 * its nearest kept neighbours. A single drag therefore rewrites exactly one row, whichever
 * direction it went — a greedy left-to-right pass would renumber everything a row jumped over
 * on the way up.
 *
 * Returns one entry per input: the new key, or null where the row keeps its own.
 */
fun rekeyForOrder(keys: List<String>): List<String?> {
    val n = keys.size
    if (n == 0) return emptyList()
    val valid = keys.map(FractionalIndex::isValid)

    // Patience-sort LIS over the valid keys, strictly increasing.
    val tailIdx = IntArray(n)
    val prev = IntArray(n) { -1 }
    var len = 0
    for (i in 0 until n) {
        if (!valid[i]) continue
        var lo = 0
        var hi = len
        while (lo < hi) {
            val mid = (lo + hi) ushr 1
            if (keys[tailIdx[mid]] < keys[i]) lo = mid + 1 else hi = mid
        }
        if (lo > 0) prev[i] = tailIdx[lo - 1]
        tailIdx[lo] = i
        if (lo == len) len++
    }
    val keep = BooleanArray(n)
    if (len > 0) {
        var k = tailIdx[len - 1]
        while (k >= 0) {
            keep[k] = true
            k = prev[k]
        }
    }

    val out = arrayOfNulls<String>(n)
    var i = 0
    while (i < n) {
        if (keep[i]) {
            i++
            continue
        }
        var j = i
        while (j < n && !keep[j]) j++
        val lo = if (i > 0) keys[i - 1] else null
        val hi = if (j < n) keys[j] else null
        FractionalIndex.nKeysBetween(lo, hi, j - i).forEachIndexed { off, key -> out[i + off] = key }
        i = j
    }
    return out.toList()
}
