-- Naice Notes sync backend — initial schema.
--
-- Model: users belong to spaces (exactly one personal space each, plus any number of shared
-- ones). Sections belong to a space; items belong to a section. Row-level security is the
-- only security boundary: the anon key and project URL ship in the public PWA bundle.
--
-- Sync protocol (both clients):
--   push  — upsert dirty rows by client-generated uuid; deletes are tombstones (deleted_at).
--   pull  — select rows with rev > cursor - REV_OVERLAP, apply idempotently, advance cursor.
--   rev is set from one global sequence by trigger on every write, so device clocks never
--   order anything. Sequence values are handed out before commit, so a slow transaction can
--   commit a lower rev after a faster one with a higher rev; clients therefore re-read a small
--   overlap window behind their cursor. Applying a row twice is harmless.
--
-- Rows never change space. A section's space_id is immutable, and an item can only move to
-- a section in the same space. Otherwise whoever loses access would never see the row leave
-- and keep a ghost copy. Clients express a cross-space move as tombstone + insert.

-- ─── Spaces & membership ────────────────────────────────────────────────────────────────

create table public.spaces (
  id          uuid primary key default gen_random_uuid(),
  name        text not null check (length(trim(name)) > 0),
  kind        text not null check (kind in ('personal', 'shared')),
  created_by  uuid not null references auth.users (id) on delete cascade,
  created_at  timestamptz not null default now()
);

create unique index spaces_one_personal_per_user on public.spaces (created_by) where kind = 'personal';

create table public.space_members (
  space_id   uuid not null references public.spaces (id) on delete cascade,
  user_id    uuid not null references auth.users (id) on delete cascade,
  role       text not null default 'member' check (role in ('owner', 'member')),
  joined_at  timestamptz not null default now(),
  primary key (space_id, user_id)
);

create index space_members_user on public.space_members (user_id);

-- An invite with space_id = null only allows an account to be created (used once, to let the
-- first user in before any shared space exists).
create table public.space_invites (
  id           uuid primary key default gen_random_uuid(),
  space_id     uuid references public.spaces (id) on delete cascade,
  email        text not null check (email = lower(trim(email)) and email like '%@%'),
  invited_by   uuid references auth.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  accepted_at  timestamptz,
  unique nulls not distinct (space_id, email)
);

create index space_invites_open_email on public.space_invites (email) where accepted_at is null;

-- ─── Synced content ─────────────────────────────────────────────────────────────────────

create sequence public.sync_rev_seq;

-- Deliberately no remote_kind column: the Claude section is device-only. PostgREST rejects a
-- payload naming an unknown column, so a client that tried to upload it fails loudly.
create table public.sections (
  id          uuid primary key,                       -- generated by the client
  space_id    uuid not null references public.spaces (id) on delete cascade,
  name        text not null,
  color       integer not null,                       -- ARGB, as Android stores it
  emoji       text,
  sort_key    text collate "C" not null,              -- fractional index; byte order on every side
  created_at  bigint not null,                        -- epoch millis, client clock (display only)
  updated_at  timestamptz not null default now(),     -- server-set
  deleted_at  timestamptz,
  rev         bigint not null default nextval('public.sync_rev_seq')
);

create index sections_space_rev on public.sections (space_id, rev);

create table public.items (
  id                 uuid primary key,                -- generated by the client
  section_id         uuid not null references public.sections (id) on delete cascade,
  text               text not null,
  is_checked         boolean not null default false,
  sort_key           text collate "C" not null,
  created_at         bigint not null,                 -- epoch millis, client clock
  created_by         uuid references auth.users (id) on delete set null,
  link_url           text,
  link_title         text,
  link_image_url     text,
  link_fetch_failed  boolean not null default false,
  due_at             bigint,                          -- epoch millis, same as Android
  repeat_weeks       integer check (repeat_weeks is null or repeat_weeks > 0),
  updated_at         timestamptz not null default now(),
  deleted_at         timestamptz,
  rev                bigint not null default nextval('public.sync_rev_seq')
);

create index items_section on public.items (section_id);
create index items_rev on public.items (rev);

-- Lowest rev a client may still hold as a cursor. Raised when tombstones are purged: a client
-- whose cursor is below it may have missed a delete and must do a full resync.
create table public.sync_horizon (
  id       integer primary key default 1 check (id = 1),
  min_rev  bigint not null default 0
);
insert into public.sync_horizon default values;

-- ─── Helpers (security definer so policies don't recurse through space_members' own RLS) ──

create function public.is_member(p_space uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.space_members m
    where m.space_id = p_space and m.user_id = auth.uid()
  );
$$;

create function public.section_space(p_section uuid)
returns uuid
language sql stable security definer set search_path = ''
as $$
  select s.space_id from public.sections s where s.id = p_section;
$$;

-- ─── Write triggers ─────────────────────────────────────────────────────────────────────

create function public.stamp_rev()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  new.rev := nextval('public.sync_rev_seq');
  new.updated_at := now();
  return new;
end;
$$;

create trigger sections_stamp before insert or update on public.sections
  for each row execute function public.stamp_rev();

create trigger items_stamp before insert or update on public.items
  for each row execute function public.stamp_rev();

create function public.guard_section_update()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.space_id is distinct from old.space_id then
    raise exception 'sections cannot change space; tombstone and re-create instead'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger sections_guard before update on public.sections
  for each row execute function public.guard_section_update();

-- Tombstoning a section tombstones its live items, so a client that only watches item revs
-- still learns they're gone. Reviving a section does not revive items; the client re-pushes
-- the ones it still has.
create function public.cascade_section_tombstone()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.deleted_at is not null and old.deleted_at is null then
    update public.items set deleted_at = new.deleted_at
    where section_id = new.id and deleted_at is null;
  end if;
  return null;
end;
$$;

create trigger sections_cascade_tombstone after update on public.sections
  for each row execute function public.cascade_section_tombstone();

create function public.guard_item_write()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := coalesce(new.created_by, auth.uid());
  else
    new.created_by := old.created_by;  -- authorship is not editable
    if new.section_id is distinct from old.section_id
       and public.section_space(new.section_id) is distinct from public.section_space(old.section_id) then
      raise exception 'items cannot move between spaces; tombstone and re-create instead'
        using errcode = 'check_violation';
    end if;
  end if;
  return new;
end;
$$;

create trigger items_guard before insert or update on public.items
  for each row execute function public.guard_item_write();

-- ─── Account lifecycle ──────────────────────────────────────────────────────────────────

-- Auth hook "before user created": only invited emails may get an account. Register it in
-- the dashboard under Authentication → Hooks → Before User Created → Postgres function.
create function public.hook_before_user_created(event jsonb)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_email text := lower(trim(event -> 'user' ->> 'email'));
begin
  if v_email is not null and exists (
    select 1 from public.space_invites i
    where i.email = v_email and i.accepted_at is null
  ) then
    return '{}'::jsonb;
  end if;
  return jsonb_build_object(
    'error', jsonb_build_object('http_code', 403, 'message', 'This app is invite-only.')
  );
end;
$$;

-- After an account exists: personal space, then every open invite becomes a membership.
create function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_space uuid;
begin
  insert into public.spaces (name, kind, created_by)
  values ('Personal', 'personal', new.id)
  returning id into v_space;

  insert into public.space_members (space_id, user_id, role) values (v_space, new.id, 'owner');

  insert into public.space_members (space_id, user_id, role)
  select i.space_id, new.id, 'member'
  from public.space_invites i
  where i.email = lower(new.email) and i.accepted_at is null and i.space_id is not null
  on conflict do nothing;

  update public.space_invites set accepted_at = now()
  where email = lower(new.email) and accepted_at is null;

  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.create_shared_space(p_name text)
returns uuid
language plpgsql security definer set search_path = ''
as $$
declare
  v_space uuid;
begin
  if auth.uid() is null then
    raise exception 'not signed in' using errcode = 'insufficient_privilege';
  end if;
  insert into public.spaces (name, kind, created_by) values (p_name, 'shared', auth.uid())
  returning id into v_space;
  insert into public.space_members (space_id, user_id, role) values (v_space, auth.uid(), 'owner');
  return v_space;
end;
$$;

-- Invite someone into a shared space you belong to. If they already have an account they join
-- immediately; otherwise the invite waits for their first sign-in.
create function public.invite_to_space(p_space uuid, p_email text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_email text := lower(trim(p_email));
  v_user  uuid;
begin
  if not public.is_member(p_space) then
    raise exception 'not a member of this space' using errcode = 'insufficient_privilege';
  end if;
  if (select kind from public.spaces where id = p_space) <> 'shared' then
    raise exception 'personal spaces cannot be shared' using errcode = 'check_violation';
  end if;

  select id into v_user from auth.users where lower(email) = v_email;

  insert into public.space_invites (space_id, email, invited_by, accepted_at)
  values (p_space, v_email, auth.uid(), case when v_user is not null then now() end)
  on conflict (space_id, email) do nothing;

  if v_user is not null then
    insert into public.space_members (space_id, user_id, role)
    values (p_space, v_user, 'member')
    on conflict do nothing;
  end if;
end;
$$;

-- Hard-deletes tombstones older than p_age and raises the horizon past them. Schedule with
-- pg_cron once enabled, e.g. select cron.schedule('purge', '0 4 * * *', $$select public.purge_tombstones()$$);
create function public.purge_tombstones(p_age interval default interval '30 days')
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_max bigint;
begin
  select max(rev) into v_max from (
    select rev from public.items    where deleted_at < now() - p_age
    union all
    select rev from public.sections where deleted_at < now() - p_age
  ) t;
  if v_max is null then return; end if;
  delete from public.items    where deleted_at < now() - p_age;
  delete from public.sections where deleted_at < now() - p_age;
  update public.sync_horizon set min_rev = greatest(min_rev, v_max);
end;
$$;

-- ─── Privileges ─────────────────────────────────────────────────────────────────────────

revoke all on public.spaces, public.space_members, public.space_invites,
              public.sections, public.items, public.sync_horizon from anon, authenticated;

grant select on public.spaces, public.space_members, public.space_invites, public.sync_horizon to authenticated;
grant update (name) on public.spaces to authenticated;
-- No DELETE: content is removed by tombstoning, so the other device hears about it.
grant select, insert, update on public.sections, public.items to authenticated;
grant usage on sequence public.sync_rev_seq to authenticated;  -- stamp_rev runs as the caller

revoke execute on all functions in schema public from public, anon;
grant execute on function public.is_member(uuid), public.section_space(uuid),
                          public.create_shared_space(text), public.invite_to_space(uuid, text)
  to authenticated;
revoke execute on function public.hook_before_user_created(jsonb) from authenticated;
revoke execute on function public.purge_tombstones(interval) from authenticated;
grant usage on schema public to supabase_auth_admin;
grant execute on function public.hook_before_user_created(jsonb) to supabase_auth_admin;

-- ─── Row-level security ─────────────────────────────────────────────────────────────────

alter table public.spaces        enable row level security;
alter table public.space_members enable row level security;
alter table public.space_invites enable row level security;
alter table public.sections      enable row level security;
alter table public.items         enable row level security;
alter table public.sync_horizon  enable row level security;

create policy spaces_read on public.spaces for select to authenticated
  using (public.is_member(id));
create policy spaces_rename on public.spaces for update to authenticated
  using (exists (select 1 from public.space_members m
                 where m.space_id = id and m.user_id = auth.uid() and m.role = 'owner'));

create policy members_read on public.space_members for select to authenticated
  using (public.is_member(space_id));

create policy invites_read on public.space_invites for select to authenticated
  using (invited_by = auth.uid() or (space_id is not null and public.is_member(space_id)));

create policy horizon_read on public.sync_horizon for select to authenticated using (true);

create policy sections_read on public.sections for select to authenticated
  using (public.is_member(space_id));
create policy sections_insert on public.sections for insert to authenticated
  with check (public.is_member(space_id));
create policy sections_update on public.sections for update to authenticated
  using (public.is_member(space_id)) with check (public.is_member(space_id));

create policy items_read on public.items for select to authenticated
  using (public.is_member(public.section_space(section_id)));
create policy items_insert on public.items for insert to authenticated
  with check (public.is_member(public.section_space(section_id)));
create policy items_update on public.items for update to authenticated
  using (public.is_member(public.section_space(section_id)))
  with check (public.is_member(public.section_space(section_id)));

